Uint16List? _cachedGbkTable;

Uint16List _gbkTable() {
  final existing = _cachedGbkTable;
  if (existing != null) return existing;
  final compressed = base64Decode(_gbkDeltaZlibBase64);
  final raw = const ZLibDecoder().decodeBytes(compressed);
  const count = (0xFE - 0x81 + 1) * (0xFE - 0x40 + 1);
  final table = Uint16List(count);
  var prev = 0;
  for (var i = 0; i < count; i++) {
    final delta = raw[i * 2] | (raw[i * 2 + 1] << 8);
    prev = (prev + delta) & 0xFFFF;
    table[i] = prev;
  }
  _cachedGbkTable = table;
  return table;
}

/// Decodes CP936 / GBK bytes into a Dart UTF-16 [String] in pure Dart.
String decodeGbkBytes(Uint8List bytes, {bool allowMalformed = true}) {
  if (bytes.isEmpty) return '';
  final table = _gbkTable();
  final units = <int>[];
  var i = 0;
  final len = bytes.length;
  while (i < len) {
    final lead = bytes[i++];
    if (lead < 0x80) {
      units.add(lead);
      continue;
    }
    if (lead >= 0x81 && lead <= 0xFE && i < len) {
      final trail = bytes[i];
      if (trail >= 0x40 && trail <= 0xFE && trail != 0x7F) {
        i++;
        final cp = table[(lead - 0x81) * 191 + (trail - 0x40)];
        if (cp == 0xFFFD && !allowMalformed) {
          throw const FormatException('Invalid GBK byte sequence');
        }
        units.add(cp);
        continue;
      }
    }
    if (!allowMalformed) {
      throw const FormatException('Invalid GBK byte sequence');
    }
    units.add(0xFFFD);
  }
  return String.fromCharCodes(units);
}

